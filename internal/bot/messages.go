// errorQuip explains common failures in pelmeni terms (the technical reason
// is still shown below it).
func errorQuip(reason string) string {
	r := lower(reason)
	switch {
	case contains(r, "login", "log in", "sign in", "authentication", "cookies", "private", "requires authentication"):
		return "🪪 Сайт требует паспорт, а у пельменей только справка из морозилки. Нужны свежие cookies."
	case contains(r, "unsupported url", "no video could be found", "no downloadable", "contains no", "no video formats"):
		return "🔍 Пельмени обыскали всю страницу и не нашли ни одного видео. Только тесто."
	case contains(r, "not available", "unavailable", "removed", "deleted", "404", "does not exist"):
		return "🫥 Видео исчезло раньше, чем пельмени всплыли. Возможно, его удалили."
	case contains(r, "timed out", "timeout", "deadline exceeded"):
		return "🧊 Бульон остыл, пока сайт думал. Попробуй ещё раз чуть позже."
	case contains(r, "403", "forbidden", "blocked", "rate limit", "rate-limit", "too many requests", "429"):
		return "🚧 Сайт выставил вышибалу. Пельмени не прошли дресс-код."
	case contains(r, "ffmpeg", "encode", "remux", "codec"):
		return "🔥 Кастрюля не справилась с варкой. ffmpeg что-то бормочет про кодеки."
	}
	return ""
}
